void FontGetCell( char c, int *pnColumn, int *pnRow )
{
    int nIndex = (unsigned char)c - FONT_FIRST_CHAR;
    if ( nIndex < 0 || nIndex >= FONT_COLUMNS * FONT_ROWS )
        nIndex = 0;
    *pnColumn = nIndex % FONT_COLUMNS;
    *pnRow    = nIndex / FONT_COLUMNS;
}

void FontBuildAtlas( uint8_t *pOut )
{
    memset( pOut, 0, (size_t)FONT_ATLAS_W * FONT_ATLAS_H );

    for ( int i = 0; i < GLYPH_COUNT; ++i )
    {
        const SGlyph &glyph = GLYPHS[ i ];
        int nColumn, nRow;
        FontGetCell( glyph.ch, &nColumn, &nRow );

        const int nBaseX = nColumn * FONT_CELL_W;
        const int nBaseY = nRow * FONT_CELL_H;

        for ( int y = 0; y < 7; ++y )
        {
            const char *pszRow = glyph.rows[ y ];
            for ( int x = 0; x < 5 && pszRow[ x ]; ++x )
            {
                if ( pszRow[ x ] == '#' )
                    pOut[ ( nBaseY + y ) * FONT_ATLAS_W + ( nBaseX + x ) ] = 0xFF;
            }
        }
    }
}
